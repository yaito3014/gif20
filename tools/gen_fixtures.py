"""GIF files written by Pillow, for the decoder tests in test/.

The images are built from the formulas below, which test/fixtures.hpp
repeats to compute the expected palettes and pixels, so the tests check the
decoder against an independent encoder rather than against itself.

usage: uv run tools/gen_fixtures.py > test/pillow_fixtures.inc
"""

import io

from PIL import Image


def still() -> Image.Image:
    # mirrors still_palette() and still_pixels() in test/fixtures.hpp
    im = Image.new("P", (8, 8))
    im.putpalette([0, 0, 0, 255, 0, 0, 0, 255, 0, 0, 0, 255])
    im.putdata([(i * i + i // 3) % 4 for i in range(64)])
    return im


def animation_frame(k: int) -> Image.Image:
    # mirrors animation_palette(k) and animation_pixels(k) in test/fixtures.hpp
    colors = 3 + k
    im = Image.new("P", (16, 12))
    im.putpalette([(c * (k + 1) * 37) % 256 for c in range(3 * colors)])
    im.putdata(
        [(x * (k + 2) + y * 3 + k) % colors for y in range(12) for x in range(16)]
    )
    return im


def array(name: str, data: bytes) -> str:
    lines = [
        ", ".join(f"0x{b:02X}" for b in data[i : i + 16])
        for i in range(0, len(data), 16)
    ]
    body = ",\n    ".join(lines)
    return f"inline constexpr std::array<unsigned char, {len(data)}> {name}{{\n    {body},\n}};\n"


def main() -> None:
    buf = io.BytesIO()
    still().save(buf, "GIF", interlace=False, optimize=False)
    still_gif = buf.getvalue()

    frames = [animation_frame(k) for k in range(3)]
    buf = io.BytesIO()
    frames[0].save(
        buf,
        "GIF",
        save_all=True,
        append_images=frames[1:],
        interlace=False,
        optimize=False,
        duration=100,
        loop=0,
        disposal=1,
    )
    animation_gif = buf.getvalue()

    print("// generated by tools/gen_fixtures.py with Pillow 13.0.0; do not edit")
    print()
    print("// still(): 8x8, a global palette of 4 colors, minimum code size 8")
    print(array("pillow_still", still_gif))
    print(
        "// animation_frame(0..2): 16x12, the first frame on the global palette, the others on local"
    )
    print(
        "// palettes of 4 and 8 entries, with NETSCAPE2.0 and graphic control extensions"
    )
    print(array("pillow_animation", animation_gif))


if __name__ == "__main__":
    main()
